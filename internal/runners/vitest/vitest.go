// Package vitest is the runner plugin for Vitest.
//
// Vitest's JSON reporter is Jest-compatible, so the report types and the pool
// batch report parser here mirror the Jest plugin's. The main differences
// from the Jest plugin are the default test and retry commands, and the exact
// test names kept for retries.
package vitest

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/buildkite/bktest/v3/pkg/runnerplugin"
	"github.com/kballard/go-shellquote"
)

type handler struct{}

// New returns the Vitest handler.
func New() runnerplugin.Handler { return handler{} }

var _ runnerplugin.AttemptInterpreter = handler{}

// retryNamesState is the file in the state directory that keeps the names
// Vitest matches each reported test with, by test identifier. It keeps the
// original suite boundaries for retry matching without changing collector
// identities: InterpretAttempt records them from the report, and
// PrepareAttempt builds the retry command's test name pattern from them.
const retryNamesState = "vitest-retry-names.json"

func (handler) Configure(request runnerplugin.ConfigureRequest) (runnerplugin.ConfigureResponse, error) {
	c := request.Config
	if c.TestCommand == "" {
		c.TestCommand = "npx vitest run {{testExamples}} --reporter=default --reporter=json --outputFile {{resultPath}}"
	}

	if c.TestFilePattern == "" {
		c.TestFilePattern = "**/{__tests__/**/*,*.spec,*.test}.{ts,js,tsx,jsx}"
	}

	if c.RetryTestCommand == "" {
		c.RetryTestCommand = "npx vitest run --testNamePattern '{{testNamePattern}}' --reporter=default --reporter=json --outputFile {{resultPath}}"
	}

	return runnerplugin.ConfigureResponse{
		Name:   "Vitest",
		Config: c,
		Features: runnerplugin.Features{
			SplitByFile:     true,
			SplitByExample:  false,
			FilterTestFiles: true,
			FilterTestByTag: false,
			AutoRetry:       true,
			Mute:            true,
			Skip:            false,
			SplitBySelector: true,
		},
		ResultFormat: "jest-json",
	}, nil
}

// InterpretAttempt records the tests in Vitest's JSON report, and keeps
// their exact names for retries in the state directory.
func (handler) InterpretAttempt(request runnerplugin.InterpretAttemptRequest) (runnerplugin.InterpretAttemptResponse, error) {
	// A retry by name can exit 0 without running a test that failed earlier.
	// The attempt fails when the command exits 0 but failed tests remain,
	// whether or not the report can be read.
	response := runnerplugin.InterpretAttemptResponse{
		FailedTestsMessage: "Vitest finished with failed tests; see the report above",
	}

	// Vitest exits with a non-zero status code when there are test failures,
	// so we should always attempt to parse the report even if the command returns an error.
	report, parseErr := ReadReport(request.Config.ResultPath)
	if parseErr != nil {
		// We don't want to fail the build if we fail to parse the report:
		// the attempt's error stays the command error (which can be nil), instead of the parse error.
		response.Messages = append(response.Messages, fmt.Sprintf("Buildkite Test Engine Client: Failed to read Vitest output, tests will not be retried: %v", parseErr))
		return response, nil
	}

	retryNames := make(map[string][]string)
	if _, err := runnerplugin.LoadState(request.StateDir, retryNamesState, &retryNames); err != nil {
		return runnerplugin.InterpretAttemptResponse{}, fmt.Errorf("failed to read the test names kept for retries: %v", err)
	}

	for _, testResult := range report.TestResults {
		// A TestResult with status "failed" but no AssertionResults indicates a
		// file-level runtime error (e.g. an import that throws).
		if testResult.Status == "failed" && len(testResult.AssertionResults) == 0 {
			response.RunError = "Vitest failed with runtime error test suites"
		}

		for _, example := range testResult.AssertionResults {
			var status string
			switch example.Status {
			case "failed":
				status = runnerplugin.StatusFailed
			case "passed":
				status = runnerplugin.StatusPassed
			case "pending":
				status = runnerplugin.StatusSkipped
			// Vitest reports skipped tests (it.skip / it.todo) with status
			// "skipped", whereas Jest uses "pending". Handle both.
			case "skipped":
				status = runnerplugin.StatusSkipped
			case "todo":
				status = runnerplugin.StatusSkipped
			default:
				status = runnerplugin.StatusUnknown
			}

			workDir, err := os.Getwd()
			if err != nil {
				return runnerplugin.InterpretAttemptResponse{}, fmt.Errorf("failed to get current working directory: %v", err)
			}
			testPath, err := filepath.Rel(workDir, testResult.FileName)
			if err != nil {
				return runnerplugin.InterpretAttemptResponse{}, fmt.Errorf("failed to get relative path of test file: %v", err)
			}

			// The scope and name has to match the scope generated by the Buildkite
			// test collector's Vitest reporter so splitting and collection line up
			// on the same test identities.
			testCase := runnerplugin.TestCase{
				Name:  example.Title,
				Scope: strings.Join(example.AncestorTitles, " "),
				Path:  testPath,
			}
			// A skipped assertion on a name-filtered retry didn't run, even if it
			// was requested. Keep its earlier result rather than clearing a failure.
			if request.Retry && status == runnerplugin.StatusSkipped {
				continue
			}

			// Vitest 4 matches space-separated names; Vitest 5 uses " > ".
			// JSON fullName still uses spaces in both, so derive both from titles.
			titles := append(slices.Clone(example.AncestorTitles), example.Title)
			retryNames[runnerplugin.TestIdentifier(testCase)] = slices.Compact([]string{
				strings.Join(titles, " "),
				strings.Join(titles, " > "),
			})
			response.Tests = append(response.Tests, runnerplugin.TestResult{TestCase: testCase, Status: status})
		}
	}

	if err := runnerplugin.SaveState(request.StateDir, retryNamesState, retryNames); err != nil {
		return runnerplugin.InterpretAttemptResponse{}, fmt.Errorf("failed to keep the test names for retries: %v", err)
	}

	return response, nil
}

func (handler) PrepareAttempt(request runnerplugin.PrepareAttemptRequest) (runnerplugin.PrepareAttemptResponse, error) {
	c := request.Config
	cmd := c.TestCommand
	if request.Retry {
		cmd = c.RetryTestCommand
	}

	words, err := shellquote.Split(cmd)
	if err != nil {
		return runnerplugin.PrepareAttemptResponse{}, err
	}

	testPaths := runnerplugin.Paths(request.TestCases)
	slices.Sort(testPaths)
	testPaths = slices.Compact(testPaths)

	if request.Retry {
		idx := slices.Index(words, "{{testNamePattern}}")
		if idx < 0 {
			return runnerplugin.PrepareAttemptResponse{}, fmt.Errorf("couldn't find '{{testNamePattern}}' sentinel in retry command")
		}

		retryNames := make(map[string][]string)
		if _, err := runnerplugin.LoadState(request.StateDir, retryNamesState, &retryNames); err != nil {
			return runnerplugin.PrepareAttemptResponse{}, fmt.Errorf("failed to read the test names kept for retries: %v", err)
		}

		var escapedTestCases []string
		for _, testCase := range request.TestCases {
			names := retryNames[runnerplugin.TestIdentifier(testCase)]
			if len(names) == 0 {
				// No report with the test was interpreted, such as when the test cases
				// come from elsewhere. Preserve the existing space-separated name;
				// suite boundaries cannot be recovered from Scope.
				fullName := testCase.Name
				if testCase.Scope != "" {
					fullName = testCase.Scope + " " + testCase.Name
				}
				names = []string{fullName}
			}
			for _, name := range names {
				escapedTestCases = append(escapedTestCases, regexp.QuoteMeta(name))
			}
		}

		// Match whole names, not tests whose names merely contain a failed name.
		testNamePattern := fmt.Sprintf("^(%s)$", strings.Join(escapedTestCases, "|"))
		words = slices.Replace(words, idx, idx+1, testNamePattern)

		testExamplesIdx := slices.Index(words, "{{testExamples}}")
		if testExamplesIdx >= 0 {
			words = slices.Replace(words, testExamplesIdx, testExamplesIdx+1, testPaths...)
		}
	} else {
		idx := slices.Index(words, "{{testExamples}}")
		if idx < 0 {
			words = append(words, testPaths...)
		} else {
			words = slices.Replace(words, idx, idx+1, testPaths...)
		}
	}

	outputIdx := slices.Index(words, "{{resultPath}}")
	if outputIdx < 0 {
		return runnerplugin.PrepareAttemptResponse{}, fmt.Errorf("couldn't find '{{resultPath}}' sentinel in command, exiting")
	}
	words = slices.Replace(words, outputIdx, outputIdx+1, c.ResultPath)

	return runnerplugin.PrepareAttemptResponse{Argv: words}, nil
}

// Example is a test in a Vitest JSON report, which is Jest-compatible.
type Example struct {
	Name           string   `json:"fullName"`
	Status         string   `json:"status"`
	Title          string   `json:"title"`
	AncestorTitles []string `json:"ancestorTitles"`
	Location       struct {
		Line   int
		Column int
	}
}

// Report is the structure of Vitest's JSON report, which is Jest-compatible.
type Report struct {
	NumFailedTests int
	TestResults    []struct {
		AssertionResults []Example
		FileName         string `json:"name"`
		Status           string
	}
}

// ReadReport reads the Jest-compatible JSON report at path.
func ReadReport(path string) (Report, error) {
	var report Report
	data, err := os.ReadFile(path)
	if err != nil {
		return Report{}, fmt.Errorf("failed to read report output: %v", err)
	}

	if err := json.Unmarshal(data, &report); err != nil {
		return Report{}, fmt.Errorf("failed to parse report output: %s", err)
	}

	return report, nil
}
