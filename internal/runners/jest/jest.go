// Package jest is the runner plugin for Jest.
package jest

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/buildkite/bktest/v3/pkg/runnerplugin"
	"github.com/kballard/go-shellquote"
)

type handler struct{}

// New returns the Jest handler.
func New() runnerplugin.Handler { return handler{} }

var (
	_ runnerplugin.AttemptInterpreter = handler{}
	_ runnerplugin.BatchReportParser  = handler{}
)

func (handler) Configure(request runnerplugin.ConfigureRequest) (runnerplugin.ConfigureResponse, error) {
	c := request.Config
	if c.TestCommand == "" {
		c.TestCommand = "npx jest --runTestsByPath {{testExamples}} --json --testLocationInResults --outputFile {{resultPath}}"
	}

	if c.TestFilePattern == "" {
		c.TestFilePattern = "**/{__tests__/**/*,*.spec,*.test}.{ts,js,tsx,jsx}"
	}

	if c.RetryTestCommand == "" {
		c.RetryTestCommand = "npx jest --testNamePattern '{{testNamePattern}}' --json --testLocationInResults --outputFile {{resultPath}}"
	}

	return runnerplugin.ConfigureResponse{
		Name:   "Jest",
		Config: c,
		Features: runnerplugin.Features{
			SplitByFile:     true,
			SplitByExample:  false,
			FilterTestFiles: true,
			FilterTestByTag: false,
			AutoRetry:       true,
			Mute:            true,
			Skip:            false,
			SplitBySelector: true,
		},
		ResultFormat: "jest-json",
	}, nil
}

// InterpretAttempt records the tests in Jest's JSON report, and the files
// that failed outside their tests.
func (handler) InterpretAttempt(request runnerplugin.InterpretAttemptRequest) (runnerplugin.InterpretAttemptResponse, error) {
	var response runnerplugin.InterpretAttemptResponse

	// Jest exits with a non-zero status code when there are test failures,
	// so we should always attempt to parse the report even if the command returns an error.
	report, parseErr := ReadReport(request.Config.ResultPath)
	if parseErr != nil {
		// We don't want to fail the build if we fail to parse the report:
		// the attempt's error stays the command error (which can be nil), instead of the parse error.
		response.Messages = append(response.Messages, fmt.Sprintf("Buildkite Test Engine Client: Failed to read Jest output, tests will not be retried: %v", parseErr))
		return response, nil
	}

	workDir, err := os.Getwd()
	if err != nil {
		return runnerplugin.InterpretAttemptResponse{}, fmt.Errorf("failed to get current working directory: %v", err)
	}

	for _, testResult := range report.TestResults {
		testPath, err := filepath.Rel(workDir, testResult.FileName)
		if err != nil {
			return runnerplugin.InterpretAttemptResponse{}, fmt.Errorf("failed to get relative path of test file: %v", err)
		}

		// TestResult represents a test file result, while AssertionResult represents the individual test cases result.
		// When a TestResult has status "failed" but has no AssertionResults, it indicates a runtime error at the file level.
		// Jest still runs the other files, so their failed tests can be retried.
		if testResult.Status == "failed" && len(testResult.AssertionResults) == 0 {
			response.ErroredFiles = append(response.ErroredFiles, testPath)
		}

		for _, example := range testResult.AssertionResults {
			var status string
			switch example.Status {
			case "failed":
				status = runnerplugin.StatusFailed
			case "passed":
				status = runnerplugin.StatusPassed
			case "pending":
				status = runnerplugin.StatusSkipped
			case "todo":
				status = runnerplugin.StatusSkipped
			default:
				status = runnerplugin.StatusUnknown
			}

			// The scope and name has to match with the scope generated by Buildkite test collector.
			// For more details, see:
			// [Buildkite Test Collector - Jest implementation](https://github.com/buildkite/test-collector-javascript/blob/42b803a618a15a07edf0169038ef4b5eba88f98d/jest/reporter.js#L40)
			testCase := runnerplugin.TestCase{
				Name:  example.Title,
				Scope: strings.Join(example.AncestorTitles, " "),
				Path:  testPath,
			}

			// Retries run by name, and Jest reports the tests the name pattern
			// doesn't match as pending. Those weren't retried, so they keep their
			// earlier result, as does a retried test the pattern missed.
			if request.Retry && status == runnerplugin.StatusSkipped {
				continue
			}

			response.Tests = append(response.Tests, runnerplugin.TestResult{TestCase: testCase, Status: status})
		}
	}

	return response, nil
}

// Example is a test in a Jest JSON report.
type Example struct {
	Name           string   `json:"fullName"`
	Status         string   `json:"status"`
	Title          string   `json:"title"`
	AncestorTitles []string `json:"ancestorTitles"`
	Location       struct {
		Line   int
		Column int
	}
}

// Report is the structure of Jest's JSON report.
type Report struct {
	NumFailedTests int
	TestResults    []struct {
		AssertionResults []Example
		FileName         string `json:"name"`
		Status           string
	}
}

// ParseBatchReport handles the report of one Jest command run by bktec pool
// consume. Unlike InterpretAttempt, it validates the report and maps
// assertions to test cases for lease matching and retries.
func (handler) ParseBatchReport(request runnerplugin.ParseBatchReportRequest) (runnerplugin.ParseBatchReportResponse, error) {
	if request.Format != "jest-json" {
		return runnerplugin.ParseBatchReportResponse{}, fmt.Errorf("unsupported runner report format %q", request.Format)
	}
	data, err := os.ReadFile(request.ReportPath)
	if err != nil {
		return runnerplugin.ParseBatchReportResponse{}, err
	}
	var report struct {
		NumRuntimeErrorTestSuites int `json:"numRuntimeErrorTestSuites"`
		TestResults               *[]struct {
			AssertionResults []Example `json:"assertionResults"`
			FileName         string    `json:"name"`
			Status           string    `json:"status"`
		} `json:"testResults"`
	}
	if err := json.Unmarshal(data, &report); err != nil {
		return runnerplugin.ParseBatchReportResponse{}, fmt.Errorf("invalid Jest report: %w", err)
	}
	if report.TestResults == nil {
		return runnerplugin.ParseBatchReportResponse{}, fmt.Errorf("incomplete Jest report: missing testResults")
	}
	workDir, err := os.Getwd()
	if err != nil {
		return runnerplugin.ParseBatchReportResponse{}, err
	}
	var parsed runnerplugin.ParseBatchReportResponse
	seen := map[string]int{}
	for _, file := range *report.TestResults {
		path := file.FileName
		if filepath.IsAbs(path) {
			if path, err = filepath.Rel(workDir, path); err != nil {
				return runnerplugin.ParseBatchReportResponse{}, fmt.Errorf("failed to get relative path of test file: %w", err)
			}
		}
		path = strings.TrimPrefix(filepath.ToSlash(path), "./")
		if path == "" {
			return runnerplugin.ParseBatchReportResponse{}, fmt.Errorf("jest test file has no name")
		}
		failed := false
		for _, example := range file.AssertionResults {
			var status string
			switch example.Status {
			case "passed":
				status = runnerplugin.StatusPassed
			case "failed":
				status = runnerplugin.StatusFailed
				failed = true
			case "pending", "skipped", "todo", "disabled":
				status = runnerplugin.StatusSkipped
			default:
				return runnerplugin.ParseBatchReportResponse{}, fmt.Errorf("unknown Jest test status %q", example.Status)
			}
			// Matches the scope and name of Buildkite Test Collector, as in InterpretAttempt.
			test := runnerplugin.BatchTest{
				TestCase: runnerplugin.TestCase{Scope: strings.Join(example.AncestorTitles, " "), Name: example.Title, Path: path},
				Status:   status,
				Selector: path,
			}
			if example.Location.Line > 0 {
				test.Location = fmt.Sprintf("%s:%d", path, example.Location.Line)
			}
			// Tests with the same name in one file, such as from test.each, can't be
			// told apart, so report them once: failed if any failed.
			key := strings.Join([]string{path, test.TestCase.Scope, test.TestCase.Name}, "\x00")
			if i, ok := seen[key]; ok {
				if status == runnerplugin.StatusFailed || parsed.Tests[i].Status == runnerplugin.StatusSkipped {
					parsed.Tests[i].Status = status
				}
				continue
			}
			seen[key] = len(parsed.Tests)
			parsed.Tests = append(parsed.Tests, test)
		}
		// A file that fails without a failed test, for example because it didn't
		// load or an afterAll hook threw, failed outside its tests.
		if file.Status == "failed" && !failed {
			parsed.ErroredFiles = append(parsed.ErroredFiles, path)
		}
	}
	// A file can also fail outside its tests, such as in an afterAll hook, when
	// some of its tests failed. The report counts these files without naming
	// them, so they error every test in the batch. Otherwise a muted failure or
	// a passing retry could hide the error.
	if report.NumRuntimeErrorTestSuites > len(parsed.ErroredFiles) {
		parsed.ErrorsOutsideTests = true
	}
	return parsed, nil
}

// ReadReport reads the Jest JSON report at path.
func ReadReport(path string) (Report, error) {
	var report Report
	data, err := os.ReadFile(path)
	if err != nil {
		return Report{}, fmt.Errorf("failed to read report output: %v", err)
	}

	if err := json.Unmarshal(data, &report); err != nil {
		return Report{}, fmt.Errorf("failed to parse report output: %s", err)
	}

	return report, nil
}

func (handler) PrepareAttempt(request runnerplugin.PrepareAttemptRequest) (runnerplugin.PrepareAttemptResponse, error) {
	words, err := commandWords(request.Config, request.TestCases, request.Retry)
	if err != nil {
		return runnerplugin.PrepareAttemptResponse{}, err
	}
	return runnerplugin.PrepareAttemptResponse{Argv: words}, nil
}

// commandWords replaces the "{{testExamples}}" placeholder in the test
// command with the test files, "{{testNamePattern}}" in the retry command
// with a pattern that matches the test cases, and "{{resultPath}}" with the
// result path.
func commandWords(c runnerplugin.Config, testCases []runnerplugin.TestCase, retry bool) ([]string, error) {
	cmd := c.TestCommand
	if retry {
		cmd = c.RetryTestCommand
	}

	words, err := shellquote.Split(cmd)
	if err != nil {
		return nil, err
	}

	testPaths := runnerplugin.Paths(testCases)
	slices.Sort(testPaths)
	testPaths = slices.Compact(testPaths)

	if retry {
		idx := slices.Index(words, "{{testNamePattern}}")
		if idx < 0 {
			return nil, fmt.Errorf("couldn't find '{{testNamePattern}}' sentinel in retry command")
		}

		// Jest matches the pattern anywhere in a test's full name, which joins its
		// describe titles and title with spaces. Anchor it so only the failed tests
		// run, not every test whose name contains one of theirs.
		escapedTestCases := make([]string, len(testCases))
		for i, testCase := range testCases {
			fullName := testCase.Name
			if testCase.Scope != "" {
				fullName = testCase.Scope + " " + testCase.Name
			}
			escapedTestCases[i] = regexp.QuoteMeta(fullName)
		}

		testNamePattern := fmt.Sprintf("^(%s)$", strings.Join(escapedTestCases, "|"))

		words = slices.Replace(words, idx, idx+1, testNamePattern)

		testExamplesIdx := slices.Index(words, "{{testExamples}}")
		if testExamplesIdx >= 0 {
			words = slices.Replace(words, testExamplesIdx, testExamplesIdx+1, testPaths...)
		}
	} else {
		idx := slices.Index(words, "{{testExamples}}")
		if idx < 0 {
			words = append(words, testPaths...)
		} else {
			words = slices.Replace(words, idx, idx+1, testPaths...)
		}
	}

	outputIdx := slices.Index(words, "{{resultPath}}")
	if outputIdx < 0 {
		return nil, fmt.Errorf("couldn't find '{{resultPath}}' sentinel in command, exiting")
	}
	words = slices.Replace(words, outputIdx, outputIdx+1, c.ResultPath)

	return words, nil
}
